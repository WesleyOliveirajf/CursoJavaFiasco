package NivelBasico.TiposDeDados;

public class DadosNaoPremitivos {
    public static void main(String[] args) {
        String nome = "Naruto Uzumaki";
        String nometouppercase = nome.toUpperCase(); // Caixa Alta
        System.out.println ( nometouppercase);
        System.out.println(nome);

        String aldeia = "Aldeia da Folha";
        String aldeiaCaixaBaixa = aldeia.toLowerCase(); // Caixa Baixa
        System.out.println(aldeia);
        System.out.println(aldeiaCaixaBaixa);



    }

}